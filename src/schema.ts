import type { DatabaseSync } from 'node:sqlite';
import type { Database } from './database.js';

export const tables = {
  player: `id INTEGER PRIMARY KEY, name TEXT NOT NULL, coins INTEGER NOT NULL CHECK(coins>=0),
    tokens INTEGER NOT NULL DEFAULT 0, pity INTEGER NOT NULL DEFAULT 0, unique_pity INTEGER NOT NULL DEFAULT 0, pulls INTEGER NOT NULL DEFAULT 0,
    equipped TEXT NOT NULL, share TEXT, created INTEGER NOT NULL`,
  pets: `species TEXT NOT NULL, copies INTEGER NOT NULL DEFAULT 1, xp INTEGER NOT NULL DEFAULT 0,
    hunger REAL NOT NULL DEFAULT 85, happiness REAL NOT NULL DEFAULT 85,
    energy REAL NOT NULL DEFAULT 85, hygiene REAL NOT NULL DEFAULT 85,
    sleeping INTEGER NOT NULL DEFAULT 0, updated INTEGER NOT NULL, cooldowns TEXT NOT NULL DEFAULT '{}',
    player_id INTEGER NOT NULL DEFAULT 1 REFERENCES player(id), PRIMARY KEY(player_id,species)`,
  usage: `source TEXT NOT NULL, key TEXT NOT NULL, input INTEGER NOT NULL, output INTEGER NOT NULL,
    player_id INTEGER NOT NULL DEFAULT 1 REFERENCES player(id), PRIMARY KEY(player_id,source,key)`,
  connections: `source TEXT NOT NULL, last_seen INTEGER NOT NULL, tokens INTEGER NOT NULL DEFAULT 0,
    player_id INTEGER NOT NULL DEFAULT 1 REFERENCES player(id), PRIMARY KEY(player_id,source)`,
  ledger: `id INTEGER PRIMARY KEY, kind TEXT NOT NULL, label TEXT NOT NULL, coins INTEGER NOT NULL, created INTEGER NOT NULL,
    player_id INTEGER NOT NULL DEFAULT 1 REFERENCES player(id)`,
  requests: `key TEXT NOT NULL, fingerprint TEXT NOT NULL, result TEXT NOT NULL,
    player_id INTEGER NOT NULL DEFAULT 1 REFERENCES player(id), PRIMARY KEY(player_id,key)`,
  reward_progress: `id INTEGER PRIMARY KEY REFERENCES player(id), coin_tokens INTEGER NOT NULL, xp_tokens INTEGER NOT NULL`,
  checkins: `day TEXT NOT NULL, streak INTEGER NOT NULL, coins INTEGER NOT NULL, created INTEGER NOT NULL,
    player_id INTEGER NOT NULL DEFAULT 1 REFERENCES player(id), PRIMARY KEY(player_id,day)`,
  daily_tokens: `day TEXT NOT NULL, tokens INTEGER NOT NULL DEFAULT 0,
    player_id INTEGER NOT NULL DEFAULT 1 REFERENCES player(id), PRIMARY KEY(player_id,day)`,
  accounts: `player_id INTEGER PRIMARY KEY REFERENCES player(id), username TEXT NOT NULL UNIQUE,
    nickname TEXT NOT NULL, password TEXT NOT NULL, created INTEGER NOT NULL`,
  sessions: `hash TEXT PRIMARY KEY, player_id INTEGER NOT NULL REFERENCES player(id), created INTEGER NOT NULL, expires INTEGER NOT NULL`,
  api_tokens: `id TEXT PRIMARY KEY, player_id INTEGER NOT NULL REFERENCES accounts(player_id), label TEXT NOT NULL,
    prefix TEXT NOT NULL, hash TEXT NOT NULL UNIQUE, created INTEGER NOT NULL, expires INTEGER NOT NULL, last_used INTEGER`,
};

const indexes = [
  'CREATE INDEX IF NOT EXISTS ledger_player ON ledger(player_id,id DESC)',
  'CREATE INDEX IF NOT EXISTS pets_growth ON pets(player_id,xp DESC,species)',
  'CREATE UNIQUE INDEX IF NOT EXISTS player_share ON player(share)',
  'CREATE INDEX IF NOT EXISTS sessions_player ON sessions(player_id,created)',
  'CREATE UNIQUE INDEX IF NOT EXISTS tokens_player ON api_tokens(player_id)',
  'CREATE INDEX IF NOT EXISTS daily_tokens_day ON daily_tokens(day)',
];

export async function initializeExternalDatabase(db: Database) {
  for (const [name, definition] of Object.entries(tables)) {
    let columns = definition.replace(/\bINTEGER\b/g, 'BIGINT').replace(/\bREAL\b/g, 'DOUBLE PRECISION');
    if (db.driver === 'mariadb') {
      columns = columns.replace(/\b(\w+) TEXT\b/g, (_, column: string) => `${column} ${['label', 'result', 'cooldowns'].includes(column) ? 'LONGTEXT' : 'VARCHAR(255)'}`);
      if (['player', 'ledger'].includes(name)) columns = columns.replace('id BIGINT PRIMARY KEY', 'id BIGINT AUTO_INCREMENT PRIMARY KEY');
    } else if (['player', 'ledger'].includes(name)) {
      columns = columns.replace('id BIGINT PRIMARY KEY', `id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH ${name === 'player' ? 2 : 1}) PRIMARY KEY`);
    }
    await db.exec(`CREATE TABLE IF NOT EXISTS ${name} (${columns})${db.driver === 'mariadb' ? ' ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin' : ''}`);
  }
  for (const sql of indexes) await db.exec(sql);
}

export function initializeDatabase(db: DatabaseSync) {
  db.exec('PRAGMA journal_mode=WAL; PRAGMA foreign_keys=ON; PRAGMA busy_timeout=5000; BEGIN IMMEDIATE');
  try {
    for (const [name, columns] of Object.entries(tables)) db.exec(`CREATE TABLE IF NOT EXISTS ${name} (${columns})`);
    db.exec(indexes.join(';') + ';COMMIT');
  } catch (error) { db.exec('ROLLBACK'); throw error; }
}
