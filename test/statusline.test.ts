import type { AddressInfo } from 'node:net';

import test from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { once } from 'node:events';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { stripVTControlCharacters } from 'node:util';
import { createServer } from 'node:http';
import { configuration, credential } from '../dist/src/config.js';
import { startServer } from '../dist/src/server.js';
import { shellQuote } from '../dist/src/shell-install.js';
import { powershellQuote, windowsStatuslineShell } from '../dist/src/windows.js';

test('Claude statusline preserves agent HUD and JSON input alongside the pixel character', async t => {
  const dir = mkdtempSync(join(tmpdir(), 'tokenpet-statusline-'));
  const config = configuration({ TOKENPET_DATA_DIR: dir, TOKENPET_WATCH: '0', CODEX_HOME: join(dir, 'codex'), CLAUDE_CONFIG_DIR: join(dir, 'claude') });
  const app = await startServer(config, { port: 0 });
  t.after(async () => { await app.close(); rmSync(dir, { recursive: true, force: true }); });
  const env: NodeJS.ProcessEnv = { ...process.env, TOKENPET_DATA_DIR: dir, CODEX_HOME: join(dir, 'codex'), CLAUDE_CONFIG_DIR: join(dir, 'claude'), TOKENPET_SERVER: app.url, TOKENPET_API_KEY: credential(config), COLUMNS: '100', LINES: '50', NO_COLOR: '1' };
  delete env.TOKENPET_API_KEY_FILE;
  const input = JSON.stringify({ session_id: 'test-session', workspace: { current_dir: dir }, tasks: [{ id: 'review', status: 'running' }] }) + '\n';
  const capture = join(dir, 'received.json'), script = join(dir, 'hud.mjs');
  const hud = '\x1b[32m2 active agents\x1b[0m\nreview: running\nbackend: waiting';
  writeFileSync(script, `import { readFileSync, writeFileSync } from 'node:fs'; writeFileSync(${JSON.stringify(capture)}, readFileSync(0)); console.log(${JSON.stringify(hud)});`);
  const powershell = process.platform === 'win32' && windowsStatuslineShell() === 'powershell.exe';
  const quote = powershell ? powershellQuote : shellQuote;
  const command = `${powershell ? '& ' : ''}${quote(process.execPath.replaceAll('\\', '/'))} ${quote(script.replaceAll('\\', '/'))}`;
  const previous = join(dir, 'previous-statusline.json');
  writeFileSync(previous, JSON.stringify({ type: 'command', command }));
  const run = async (values: NodeJS.ProcessEnv) => {
    const child = spawn(process.execPath, [resolve('bin/tokenpet.mjs'), 'statusline'], { env: values, stdio: ['pipe', 'pipe', 'pipe'] });
    const timeout = setTimeout(() => child.kill(), 10000);
    let stdout = '', stderr = '';
    child.stdout.on('data', data => stdout += data);
    child.stderr.on('data', data => stderr += data);
    child.stdin.end(input);
    const [code] = await once(child, 'close'); clearTimeout(timeout);
    assert.equal(code, 0, stderr);
    return stdout.trimEnd();
  };
  const output = await run(env);
  assert.ok(output.startsWith(hud + '\n'), 'previous agent output, including colors, remains intact');
  assert.equal(readFileSync(capture, 'utf8'), input, 'the prior HUD receives the original JSON unchanged');
  assert.equal(stripVTControlCharacters(output).split('\n').length, 9);
  assert.match(output.slice(hud.length), /[▀▄█]/u, 'an existing HUD must not replace the pixel character with an emoticon');
  assert.ok(output.includes((await app.game.state()).active.name));
  const shortHud = await run({ ...env, LINES: '24' });
  assert.ok(shortHud.startsWith(hud + '\n'));
  assert.equal(shortHud.split('\n').length, 9);
  assert.match(shortHud.slice(hud.length), /[▀▄█]/u);
  const stalled = createServer((_request, response) => { response.writeHead(200, { 'Content-Type': 'application/json' }); response.write('{'); });
  await new Promise<void>(resolve => stalled.listen(0, '127.0.0.1', resolve));
  t.after(() => new Promise(resolve => { stalled.closeAllConnections(); stalled.close(resolve); }));
  const began = Date.now();
  const fallback = await run({ ...env, TOKENPET_SERVER: `http://127.0.0.1:${(stalled.address() as AddressInfo).port}` });
  assert.ok(Date.now() - began < 4000, 'a stalled response body cannot starve the HUD refresh');
  assert.ok(fallback.startsWith(hud + '\n'));
  assert.ok(fallback.endsWith('작업실 쉬는 중'));
  rmSync(previous);
  const small = await run({ ...env, LINES: '24' });
  assert.equal(small.split('\n').length, 6, 'short terminals retain the pixel character');
  assert.match(small, /[▀▄█]/u);
  const narrow = await run({ ...env, COLUMNS: '32', LINES: '24' });
  assert.equal(narrow.split('\n').length, 9);
  assert.match(narrow, /[▀▄█]/u);
  const wide = await run(env);
  assert.equal(wide.split('\n').length, 6, 'large terminals without another HUD retain the pixel pet');
});
